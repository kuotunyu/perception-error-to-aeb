def test_the_ego_is_drawn_as_its_own_footprint() -> None:
    """A dot would hide exactly the geometry the threat assessment used."""

    replay = load_replay_module()

    polygon = replay.frame_polygons(frame(0))["ego"]

    assert len(polygon) == 5  # four corners, closed back to the first


def test_a_polygon_is_closed_for_drawing() -> None:
    """An open ring draws as a three-sided box, which reads as a bug in the data."""

    replay = load_replay_module()

    polygon = replay.frame_polygons(frame(0))["ego"]

    assert polygon[0] == polygon[-1]


def test_each_track_is_drawn_separately() -> None:
    """One shape per object, so a reader can follow an identity across frames."""

    replay = load_replay_module()
    one = frame(0, tracks=(track("t-0001", 40.0), track("t-0002", 20.0)))

    polygons = replay.frame_polygons(one)

    assert "t-0001" in polygons
    assert "t-0002" in polygons


def test_a_dropped_track_is_still_drawn() -> None:
    """It is drawn as dropped, not omitted.

    Omitting it would make a missed intervention look inexplicable, which is
    the opposite of what this replay is for.
    """

    replay = load_replay_module()
    one = frame(0, tracks=(track("t-0001", 40.0, visible=False),))

    assert "t-0001" in replay.frame_polygons(one)
    assert replay.frame_styles(one)["t-0001"] == replay.STYLE_UNOBSERVED


def test_an_observed_track_is_styled_differently() -> None:
    """The pair to the test above; one style for both would say nothing."""

    replay = load_replay_module()

    assert replay.frame_styles(frame(0))["t-0001"] == replay.STYLE_OBSERVED


def test_the_styles_are_distinct() -> None:
    """Two names that resolved to one value would make the distinction invisible."""

    replay = load_replay_module()

    assert replay.STYLE_OBSERVED != replay.STYLE_UNOBSERVED


