def test_the_animation_is_written_as_self_contained_html(tmp_path: Any) -> None:
    """The site must open from a file with no network and no build step."""

    replay = load_replay_module()
    path = tmp_path / "replay.html"

    replay.write_replay_html(timeline(), title="s-0001 / oracle_aeb", path=path)
    written = path.read_text(encoding="utf-8")

    assert written.lstrip().startswith("<")
    assert "plotly" in written.lower()
    assert "Derived visualization" in written
    assert "CC BY-NC-SA 4.0" in written
    assert "Plotly.js is MIT licensed" in written


def test_the_written_html_pins_its_line_ending(tmp_path: Any) -> None:
    """The same rule as every other artifact this portfolio writes.

    A file whose bytes depend on the platform that produced it cannot be
    compared between a developer's machine and CI.
    """

    replay = load_replay_module()
    path = tmp_path / "replay.html"

    replay.write_replay_html(timeline(), title="t", path=path)

    assert b"\r\n" not in path.read_bytes()


def test_the_same_timeline_produces_the_same_html(tmp_path: Any) -> None:
    """A report that differed between builds could not be checked by rebuilding it."""

    replay = load_replay_module()
    first, second = tmp_path / "a.html", tmp_path / "b.html"

    replay.write_replay_html(timeline(), title="t", path=first)
    replay.write_replay_html(timeline(), title="t", path=second)

    assert first.read_bytes() == second.read_bytes()


def test_an_empty_timeline_is_refused() -> None:
    """There is nothing to replay, and an empty animation would look like a bug."""

    replay = load_replay_module()

    with pytest.raises(ValueError, match=r"^there\ are\ no\ frames\ to\ replay"):
        replay.build_replay_figure((), title="t")


def test_an_untitled_replay_is_refused() -> None:
    """Every figure in the report says what it is of."""

    replay = load_replay_module()

    with pytest.raises(
        ValueError, match=r"^title\ must\ name\ the\ scenario\ and\ configuration\ shown"
    ):
        replay.build_replay_figure(timeline(), title="")


def test_the_state_timeline_travels_with_the_animation() -> None:
    """Seeing the boxes without the state does not explain a missed brake."""

    replay = load_replay_module()
    frames = (frame(0, state="monitor"), frame(1, state="full_brake"))

    figure = replay.build_replay_figure(frames, title="t")

    assert "full_brake" in figure["frames"][1]["layout"]["title"]["text"]
