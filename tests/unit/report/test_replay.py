def test_a_frame_carries_only_derived_world_state() -> None:
    """The field list is the guarantee, so it is asserted rather than described."""

    import dataclasses

    replay = load_replay_module()

    names = {field.name for field in dataclasses.fields(replay.ReplayFrame)}

    assert names == {
        "time_s",
        "ego_center_xy_m",
        "ego_yaw_rad",
        "ego_size_lw_m",
        "ego_speed_mps",
        "tracks",
        "aeb_state",
        "ttc_s",
    }


def test_no_frame_field_names_a_sensor() -> None:
    """This is the module most likely to acquire a camera by accident."""

    import dataclasses

    replay = load_replay_module()
    forbidden = ("image", "camera", "lidar", "pointcloud", "sensor", "blob")

    for field in dataclasses.fields(replay.ReplayFrame):
        assert not any(word in field.name.lower() for word in forbidden)


def test_a_frame_is_frozen() -> None:
    """It is the evidence for one step of a published result."""

    import dataclasses

    load_replay_module()
    one = frame(0)

    with pytest.raises(dataclasses.FrozenInstanceError):
        one.time_s = 9.0  # type: ignore[misc]


def test_a_frame_at_a_negative_time_is_refused() -> None:
    """Time before the scenario started means the timeline was built wrongly."""

    replay = load_replay_module()

    with pytest.raises(ValueError, match=r"^time_s\ must\ be\ finite\ and\ non\-negative"):
        replay.ReplayFrame(
            time_s=-0.1,
            ego_center_xy_m=(0.0, 0.0),
            ego_yaw_rad=0.0,
            ego_size_lw_m=(4.0, 2.0),
            ego_speed_mps=10.0,
            tracks=(),
            aeb_state=replay.AEBState.MONITOR,
            ttc_s=None,
        )


