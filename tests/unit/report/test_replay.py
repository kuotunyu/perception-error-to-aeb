"""Contracts for the top-down replay, which is derived and never a recording.

The replay exists so that a reader can see WHY a configuration failed, rather
than reading that it did. That makes it evidence, and evidence has to be exactly
as trustworthy as the numbers beside it.

IT IS DERIVED, NOT RECORDED. Every frame is built from the same world state the
AEB acted on: oriented boxes, the route, the time to collision and the state
timeline. There is no camera image and no lidar point anywhere in this project,
and this module is the one most likely to acquire one by accident, so a test
asserts that nothing it produces carries a sensor payload.

IT SHOWS WHAT THE CONTROLLER SAW, NOT WHAT WAS THERE. A dropped track is drawn
as dropped. A replay that quietly showed the oracle world would make every
missed intervention look inexplicable, which is the opposite of its purpose.

THE ANIMATION IS GENERATED BY PYTHON. This project ships no first-party
JavaScript: a hand-written player would be untested code sitting between a
result and the person reading it.
"""

from __future__ import annotations

from types import ModuleType
from typing import Any

import pytest


def load_replay_module() -> ModuleType:
    """Import inside the test so a missing module is a purposeful RED failure."""

    try:
        from aebrisk.report import replay
    except ImportError:
        pytest.fail("aebrisk.report.replay is missing", pytrace=False)
    return replay


def track(track_id: str, x: float, *, visible: bool = True) -> Any:
    from aebrisk.observation.models import TrackState

    return TrackState(
        track_id=track_id,
        category="vehicle",
        center_xy_m=(x, 0.0),
        yaw_rad=0.0,
        size_lw_m=(4.0, 2.0),
        velocity_xy_mps=(0.0, 0.0),
        visible=visible,
        source_timestamp_us=1_600_000_000_000_000,
        covariance_xy=(0.0, 0.0, 0.0, 0.0),
    )


def frame(index: int, *, state: str = "monitor", tracks: tuple = ()) -> Any:
    from aebrisk.aeb.state_machine import AEBState
    from aebrisk.report.replay import ReplayFrame

    return ReplayFrame(
        time_s=index * 0.1,
        ego_center_xy_m=(index * 1.0, 0.0),
        ego_yaw_rad=0.0,
        ego_size_lw_m=(4.0, 2.0),
        ego_speed_mps=10.0,
        tracks=tracks or (track("t-0001", 40.0),),
        aeb_state=AEBState(state),
        ttc_s=2.0,
    )


def timeline(count: int = 5) -> tuple:
    return tuple(frame(index) for index in range(count))


