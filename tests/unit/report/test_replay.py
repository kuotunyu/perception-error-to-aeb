def test_the_animation_has_one_step_per_frame() -> None:
    """A reader scrubbing the timeline is scrubbing the simulation's own steps."""

    replay = load_replay_module()

    figure = replay.build_replay_figure(timeline(7), title="s-0001 / oracle_aeb")

    assert len(figure["frames"]) == 7


def test_animation_has_plotly_generated_play_pause_and_time_slider() -> None:
    replay = load_replay_module()

    figure = replay.build_replay_figure(timeline(3), title="t")

    labels = [button["label"] for button in figure["layout"]["updatemenus"][0]["buttons"]]
    assert labels == ["Play", "Pause"]
    assert [step["label"] for step in figure["layout"]["sliders"][0]["steps"]] == [
        "0.0 s",
        "0.1 s",
        "0.2 s",
    ]


def test_dense_timeline_keeps_every_frame_reachable_with_sparse_visible_ticks() -> None:
    replay = load_replay_module()

    figure = replay.build_replay_figure(timeline(31), title="t")
    steps = figure["layout"]["sliders"][0]["steps"]

    assert len(steps) == 31
    assert [step["args"][0][0] for step in steps] == [frame["name"] for frame in figure["frames"]]
    assert [step["value"] for step in steps] == [f"{index * 0.1:.1f} s" for index in range(31)]
    visible_labels = [step["label"] for step in steps if step["label"]]
    assert visible_labels[0] == "0.0 s"
    assert visible_labels[-1] == "3.0 s"
    assert len(visible_labels) <= 7
    assert figure["layout"]["sliders"][0]["ticklen"] == 0


def test_labels_and_controls_have_separate_readable_regions() -> None:
    replay = load_replay_module()

    figure = replay.build_replay_figure(timeline(), title="t")
    layout = figure["layout"]

    assert layout["yaxis"]["title"]["text"] in (None, "")
    y_explanation = next(
        annotation
        for annotation in layout["annotations"]
        if annotation["text"] == "scenario-local y (m)"
    )
    assert y_explanation["textangle"] == 0
    assert y_explanation["xref"] == "paper"
    assert y_explanation["yref"] == "paper"
    assert layout["updatemenus"][0]["y"] != layout["sliders"][0]["y"]
    assert layout["sliders"][0]["currentvalue"]["prefix"] == "time "
    assert layout["margin"]["b"] >= 120


def test_long_scenario_title_wraps_without_losing_its_identity() -> None:
    replay = load_replay_module()
    title = "scenario-with-an-intentionally-long-identity-token / observation_delayed_aeb"

    figure = replay.build_replay_figure(timeline(), title=title)
    rendered = figure["layout"]["title"]["text"]

    assert "<br>" in rendered
    assert title in rendered.replace("<br>", "")
    assert max(len(line) for line in rendered.split("<br>")[:-1]) <= 32


def test_actor_trace_indices_stay_stable_when_actors_enter_exit_or_reorder() -> None:
    replay = load_replay_module()
    frames = (
        frame(0, tracks=(track("actor-b", 20.0),)),
        frame(1, tracks=(track("actor-a", 10.0), track("actor-b", 21.0))),
        frame(2, tracks=(track("actor-b", 22.0), track("actor-a", 11.0))),
        frame(3, tracks=(track("actor-a", 12.0),)),
    )

    figure = replay.build_replay_figure(frames, title="t")

    expected_names = ["ego", "actor-a", "actor-b"]
    for animation_frame in figure["frames"]:
        assert [trace["name"] for trace in animation_frame["data"]] == expected_names
    assert figure["frames"][0]["data"][1]["x"] == ()
    assert figure["frames"][3]["data"][2]["x"] == ()


def test_serialized_frame_explicitly_clears_fill_when_actor_becomes_unobserved() -> None:
    import json

    replay = load_replay_module()
    frames = (
        frame(0, tracks=(track("actor-a", 20.0, visible=True),)),
        frame(1, tracks=(track("actor-a", 21.0, visible=False),)),
    )

    serialized = json.loads(replay.build_replay_figure(frames, title="t").to_json())

    assert serialized["frames"][0]["data"][1]["fill"] == "toself"
    assert serialized["frames"][1]["data"][1]["fill"] == "none"


